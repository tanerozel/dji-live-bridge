#!/usr/bin/env node
// Builds the iOS app's Localizable.strings, Localizable.stringsdict and InfoPlist.strings from the
// Android app's strings (mobile/android/app/src/main/res/values*/strings.xml) and the iOS
// additions in mobile/ios/strings/ios-overrides.json, so both apps say the same thing in all 15
// languages. The results are generated: edit the sources and run this again.
//
//   node mobile/ios/scripts/import-android-strings.mjs          writes the files
//   node mobile/ios/scripts/import-android-strings.mjs --check  fails if they are out of date
//
// It also fails when a language misses a string, a plural's "other" form, or one of English's
// placeholders, like the Android TranslationsTest.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const iosRoot = join(here, '..');
const androidRes = join(iosRoot, '..', 'android', 'app', 'src', 'main', 'res');
const overridesFile = join(iosRoot, 'strings', 'ios-overrides.json');
const outputRoot = join(iosRoot, 'StreamMyDrone', 'Resources');

// Android resource folder → iOS language (lproj name), in the desktop app's order.
const LANGUAGES = [
  ['values', 'en'],
  ['values-es', 'es'],
  ['values-b+zh+Hans', 'zh-Hans'],
  ['values-b+zh+Hant', 'zh-Hant'],
  ['values-ar', 'ar'],
  ['values-hi', 'hi'],
  ['values-pt', 'pt'],
  ['values-ru', 'ru'],
  ['values-fr', 'fr'],
  ['values-de', 'de'],
  ['values-ja', 'ja'],
  ['values-ko', 'ko'],
  ['values-in', 'id'],
  ['values-it', 'it'],
  ['values-tr', 'tr'],
];

// Android strings that mean nothing on iOS (its notification channel, the Android 13+
// notification permission, the Wi-Fi settings screen, the Android background limit).
const ANDROID_ONLY = new Set([
  'error_ca_bundle',
  'error_background_limit',
  'notification_channel',
  'notification_channel_description',
  'clip_address_label',
  'wifi_settings',
  'wifi_settings_failed',
]);

// Written into InfoPlist.strings rather than Localizable.
const INFO_PLIST = { NSLocalNetworkUsageDescription: 'ios_local_network_usage' };

const PLURAL_FORMS = ['zero', 'one', 'two', 'few', 'many', 'other'];

function unescapeAndroid(raw) {
  let text = raw.trim();
  // A value in double quotes keeps its spaces; the quotes themselves are not part of it.
  if (text.length >= 2 && text.startsWith('"') && text.endsWith('"')) text = text.slice(1, -1);
  text = text
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, '&');
  return text.replace(/\\(u[0-9a-fA-F]{4}|.)/g, (_, escaped) => {
    if (escaped.startsWith('u') && escaped.length === 5) return String.fromCharCode(parseInt(escaped.slice(1), 16));
    if (escaped === 'n') return '\n';
    if (escaped === 't') return '\t';
    return escaped;
  });
}

/** Android's %s / %1$s / %d / %1$d as iOS format specifiers. */
function toIosFormat(text) {
  return text.replace(/%(\d+\$)?([sd])/g, (_, position = '', type) => `%${position}${type === 's' ? '@' : 'ld'}`);
}

function readAndroid(folder) {
  const file = join(androidRes, folder, 'strings.xml');
  const xml = readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const strings = new Map();
  const plurals = new Map();
  for (const match of xml.matchAll(/<string\s+([^>]*?)>([\s\S]*?)<\/string>/g)) {
    const name = /name="([^"]+)"/.exec(match[1])?.[1];
    if (!name || /translatable="false"/.test(match[1])) continue;
    strings.set(name, unescapeAndroid(match[2]));
  }
  for (const match of xml.matchAll(/<plurals\s+name="([^"]+)"[^>]*>([\s\S]*?)<\/plurals>/g)) {
    const forms = {};
    for (const item of match[2].matchAll(/<item\s+quantity="([a-z]+)"\s*>([\s\S]*?)<\/item>/g)) {
      forms[item[1]] = unescapeAndroid(item[2]);
    }
    plurals.set(match[1], forms);
  }
  return { strings, plurals };
}

function placeholders(text) {
  return [...text.matchAll(/%(\d+\$)?(@|ld)/g)].map((match) => match[0]).sort().join(' ');
}

function stringsEscape(text) {
  return text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
}

function xmlEscape(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function buildStrings(entries) {
  const lines = ['/* Generated by mobile/ios/scripts/import-android-strings.mjs. Do not edit. */', ''];
  for (const [key, value] of entries) lines.push(`"${key}" = "${stringsEscape(value)}";`);
  return `${lines.join('\n')}\n`;
}

/**
 * A plural's forms as a stringsdict entry. The count is the plural's first number; the other
 * arguments keep their positions inside every form.
 */
function buildStringsdict(plurals) {
  const out = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<!-- Generated by mobile/ios/scripts/import-android-strings.mjs. Do not edit. -->',
    '<plist version="1.0">',
    '<dict>',
  ];
  for (const [key, forms] of plurals) {
    const positional = Object.values(forms).some((form) => /%1\$ld/.test(form));
    out.push(`\t<key>${key}</key>`, '\t<dict>');
    out.push('\t\t<key>NSStringLocalizedFormatKey</key>', `\t\t<string>${positional ? '%1$#@count@' : '%#@count@'}</string>`);
    out.push('\t\t<key>count</key>', '\t\t<dict>');
    out.push('\t\t\t<key>NSStringFormatSpecTypeKey</key>', '\t\t\t<string>NSStringPluralRuleType</string>');
    out.push('\t\t\t<key>NSStringFormatValueTypeKey</key>', '\t\t\t<string>ld</string>');
    for (const form of PLURAL_FORMS) {
      if (forms[form] === undefined) continue;
      out.push(`\t\t\t<key>${form}</key>`, `\t\t\t<string>${xmlEscape(forms[form])}</string>`);
    }
    out.push('\t\t</dict>', '\t</dict>');
  }
  out.push('</dict>', '</plist>', '');
  return out.join('\n');
}

function generate() {
  const overrides = JSON.parse(readFileSync(overridesFile, 'utf8'));
  delete overrides._comment;
  const problems = [];
  const files = new Map();
  let english;

  for (const [folder, language] of LANGUAGES) {
    const android = readAndroid(folder);
    const strings = new Map();
    for (const [key, value] of android.strings) {
      if (!ANDROID_ONLY.has(key)) strings.set(key, toIosFormat(value));
    }
    for (const [key, values] of Object.entries(overrides)) {
      if (values[language] === undefined) problems.push(`${language}: ios-overrides.json has no "${key}"`);
      else strings.set(key, toIosFormat(values[language]));
    }
    const plurals = new Map();
    for (const [key, forms] of android.plurals) {
      plurals.set(key, Object.fromEntries(Object.entries(forms).map(([form, value]) => [form, toIosFormat(value)])));
    }

    if (language === 'en') {
      english = { strings, plurals };
    } else {
      for (const [key, value] of english.strings) {
        if (!strings.has(key)) problems.push(`${language}: missing "${key}"`);
        else if (placeholders(strings.get(key)) !== placeholders(value)) {
          problems.push(`${language}: "${key}" has placeholders ${placeholders(strings.get(key)) || 'none'}, English has ${placeholders(value) || 'none'}`);
        }
      }
      for (const key of strings.keys()) {
        if (!english.strings.has(key)) problems.push(`${language}: "${key}" is not in English`);
      }
      for (const [key, forms] of english.plurals) {
        const translated = plurals.get(key);
        if (!translated) problems.push(`${language}: missing plural "${key}"`);
        else if (translated.other === undefined) problems.push(`${language}: plural "${key}" has no "other" form`);
        else if (placeholders(translated.other) !== placeholders(forms.other)) {
          problems.push(`${language}: plural "${key}" changes its placeholders`);
        }
      }
    }

    const infoPlist = new Map();
    const localizable = new Map(strings);
    for (const [plistKey, key] of Object.entries(INFO_PLIST)) {
      infoPlist.set(plistKey, strings.get(key));
      localizable.delete(key);
    }
    const sorted = [...localizable.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    const directory = join(outputRoot, `${language}.lproj`);
    files.set(join(directory, 'Localizable.strings'), buildStrings(sorted));
    files.set(join(directory, 'Localizable.stringsdict'), buildStringsdict(plurals));
    files.set(join(directory, 'InfoPlist.strings'), buildStrings([...infoPlist.entries()]));
  }
  return { files, problems };
}

const check = process.argv.includes('--check');
const { files, problems } = generate();
if (problems.length > 0) {
  console.error(problems.join('\n'));
  process.exit(1);
}
let stale = 0;
for (const [file, content] of files) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    console.error(`Out of date: ${file}`);
    stale++;
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}
if (check && stale > 0) {
  console.error('Run node mobile/ios/scripts/import-android-strings.mjs');
  process.exit(1);
}
// A language folder the script no longer writes would keep stale strings in the app.
const expected = new Set(LANGUAGES.map(([, language]) => `${language}.lproj`));
const extra = existsSync(outputRoot) ? readdirSync(outputRoot).filter((name) => name.endsWith('.lproj') && !expected.has(name)) : [];
if (extra.length > 0) {
  console.error(`Unexpected language folders: ${extra.join(', ')}`);
  process.exit(1);
}
console.log(`${check ? 'Checked' : 'Wrote'} ${files.size} files for ${LANGUAGES.length} languages.`);
