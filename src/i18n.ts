const dictionaries: Record<Language, Record<string, string>> = { en, tr };
const STORAGE_KEY = "dji-live-bridge.language";

export function loadLanguage(): Language {
  const stored = localStorage.getItem(STORAGE_KEY);
  return stored === "tr" ? "tr" : "en";
}

export function saveLanguage(language: Language) {
  localStorage.setItem(STORAGE_KEY, language);
  document.documentElement.lang = language;
}

export function translate(language: Language, key: string, params: TranslationParams = {}) {
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function assertTranslationParity() {
  const englishKeys = Object.keys(en).sort();
  const turkishKeys = Object.keys(tr).sort();
  if (englishKeys.join("\n") !== turkishKeys.join("\n")) {
    throw new Error("English and Turkish translation keys do not match");
  }
  return true;
}

assertTranslationParity();
